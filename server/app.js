import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import helmet from 'helmet';
import { rateLimit } from 'express-rate-limit';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { env } from './config/env.js';
import { prisma } from './config/db.js';
import { csrfProtection } from './middleware/csrf.js';
import { errorHandler } from './middleware/errors.js';
import { validate } from './middleware/validate.js';
import { z } from 'zod';
import { AppError } from './utils/errors.js';
import { asyncHandler } from './utils/async.js';
import { webhook } from './controllers/commerce.js';
import authRoutes from './routes/auth.routes.js';
import userRoutes from './routes/user.routes.js';
import commerceRoutes from './routes/commerce.js';
import adminRoutes from './routes/admin.js';
import { legalRoutes, privacyRoutes, legalAdminRoutes } from './routes/legal.routes.js';
export const app = express();
app.disable('x-powered-by');
app.set('trust proxy',env.TRUST_PROXY);
app.use((req,res,next)=>{
  if (env.NODE_ENV === 'production' && !req.secure) return res.status(400).json({success:false,message:'Требуется защищённое соединение HTTPS'});
  next();
});
app.use(helmet({contentSecurityPolicy:{directives:{imgSrc:["'self'",'https:','data:'],scriptSrc:["'self'"],upgradeInsecureRequests:env.NODE_ENV === 'production' ? [] : null}}}));
const origins = new Set([new URL(env.CLIENT_URL).origin,new URL(env.SERVER_URL).origin]);
app.use(cors({origin:(origin,done)=>done(origin && !origins.has(origin) ? new AppError(403,'Недопустимый источник запроса') : null,true),credentials:true,methods:['GET','POST','PATCH','DELETE','OPTIONS'],allowedHeaders:['Content-Type','X-Requested-With']}));
app.use('/api',(_req,res,next)=>{res.set('Cache-Control','no-store');next();});
app.post('/api/payments/webhook',express.raw({type:'application/json',limit:'32kb'}),validate({body:z.any()}),asyncHandler(webhook));
app.use(express.json({limit:'256kb'}));
app.use(cookieParser());
app.use('/api',rateLimit({windowMs:60000,limit:300,standardHeaders:'draft-8',legacyHeaders:false,message:{success:false,message:'Слишком много запросов'}}));
app.use('/api',csrfProtection);
app.get('/api/health',validate(),asyncHandler(async (req,res)=>{ await prisma.$queryRaw`SELECT 1`; res.json({success:true,data:{status:'ok'}}); }));
app.use('/api/auth',authRoutes);
app.use('/api/legal',legalRoutes);
app.use('/api/privacy',privacyRoutes);
app.use('/api/admin/legal',legalAdminRoutes);
app.use('/api/users',userRoutes);
app.use('/api/admin',adminRoutes);
app.use('/api',commerceRoutes);
app.use('/api',(req,res,next)=>next(new AppError(404,'API endpoint не найден')));
const dist = fileURLToPath(new URL('../client/dist',import.meta.url));
if (existsSync(dist)) {
  app.use(express.static(dist));
  app.get('/{*path}',(req,res)=>res.sendFile(`${dist}/index.html`));
}
app.use((req,res,next)=>next(new AppError(404,'Страница не найдена')));
app.use(errorHandler);
